def build_md() -> str:
    names = {
        0: "プロジェクト概要", 1: "解決する課題 / 対象ユーザー", 2: "課題と根拠", 3: "既存手法との違い",
        4: "Google技術の活用例", 5: "Google技術を選定した理由", 6: "アーキテクチャ図", 7: "プロジェクトをデプロイしたURL",
        8: "テストアカウント情報", 9: "動作確認手順", 10: "サンプルデータ", 11: "主な機能", 12: "今後の展望",
        13: "AIをどの場面でどう使用したか、なぜその場面で使用したか", 14: "自分たちが開発を通して何を得て、どれくらい成長できたのか",
    }
    out = ["# プロダクト説明ドキュメント — B 担当部分の下書き", "",
           "> 黄色（docx）／【…追記】（md）は、その担当が書く場所。書いたら、【】を消す。", ""]
    out += ["- 使用した Google 技術（チェック）: ☑ Cloud Run　☑ Firebase Hosting（ほかは未使用）", ""]
    for i in range(15):
        out += [f"## {names[i]}", ""]
        for kind, text in C[i]:
            if kind == "h":
                out += [f"**{text}**", ""]
            elif kind == "p":
                out += [text, ""]
            elif kind == "b":
                out += [f"- {text}"]
            elif kind == "todo":
                out += [f"- {text}"]
            elif kind == "img":
                out += ["![アーキテクチャ図](architecture.png)", ""]
        out += [""]
    return "\n".join(out)


def build_docx(template: Path, dest: Path) -> None:
    from docx import Document
    from docx.enum.text import WD_COLOR_INDEX
    from docx.shared import Cm, Pt

    d = Document(str(template))
    # 使用した Google 技術のチェック（日本語の側だけ）
    for p in d.paragraphs[:45]:
        if p.text.strip() in ("Cloud Run", "Firebase Hosting") and p.runs:
            p.runs[0].text = "☑ " + p.runs[0].text

    def write(cell, items):
        first = True
        for kind, text in items:
            if kind == "img":
                par = cell.paragraphs[0] if first else cell.add_paragraph()
                par.add_run().add_picture(str(IMG), width=Cm(15.5))
                first = False
                continue
            par = cell.paragraphs[0] if first else cell.add_paragraph()
            first = False
            run = par.add_run(("・" if kind in ("b", "todo") else "") + text)
            run.font.size = Pt(10.5)
            if kind == "h":
                run.bold = True
            if kind == "todo":
                run.font.highlight_color = WD_COLOR_INDEX.YELLOW

    for idx in range(15):  # 日本語の側（0〜14）だけ。英語の側は、そのまま
        write(d.tables[idx].rows[0].cells[0], C[idx])
    dest.parent.mkdir(parents=True, exist_ok=True)
    d.save(str(dest))


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("使い方: build_submission_doc.py <テンプレートの docx>")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "プロダクト説明ドキュメント_Bの下書き.md").write_text(build_md(), encoding="utf-8")
    build_docx(Path(sys.argv[1]), OUT_DIR / "プロダクト説明ドキュメント_Bの下書き.docx")
    print("作成:", OUT_DIR)
